#!/usr/bin/env python3
"""Turn an Android arm64 ELF shared object into a signed-able Mach-O dylib with the same memory layout.

iOS can't map new executable pages at runtime, so the ELF image is baked into the dylib at build time:
  __ELFX (r-x): ELF vaddr [0, W0)   read-only + code segments
  __ELFW (rw-): ELF vaddr [W0, end) data, relro and bss (zero filled)
W0 is the first writable 16 KB page, and the two Mach-O segments are placed back to back, so every
PC-relative reference between code and data keeps working. Relocations, imports and TLS are applied by
the runtime loader (runtime/elfload.c) on the __ELFW copy; code pages are never written.

usage: elf2macho.py lib.so name outdir [--export sym,...] [--hook sym,...]
  -> outdir/<name>.s plus the two blobs it includes, and outdir/<name>_syms.h with
     ELF_<name>_<sym> offsets (from .symtab) for --export, and HOOK_<name>_<sym> slot offsets for --hook.
A hooked function starts with `adrp x16, slot; ldr x16, [x16, slot]; br x16`: the slots sit in an extra page
after the image (writable), and the loader fills them with the replacement functions at run time.

Every `mrs xN, tpidr_el0` is rewritten to `mrs xN, tpidrro_el0`: Darwin keeps the CPU number in TPIDR_EL0
and drops user writes, while TPIDRRO_EL0 is the thread's stable TSD base. Android code uses the thread
pointer for the stack canary ([tp, #0x28] = Darwin TSD slot 5, a constant 0) and for TLSDESC variables,
which the loader places in consecutive pthread keys of that same TSD array.
"""
import struct, sys, os

PAGE = 0x4000

def symtab(data):
    shoff, = struct.unpack_from('<Q', data, 0x28)
    shentsize, shnum = struct.unpack_from('<HH', data, 0x3a)
    secs = [struct.unpack_from('<IIQQQQIIQQ', data, shoff + i * shentsize) for i in range(shnum)]
    syms = {}
    for sh in secs:
        if sh[1] not in (2, 11):          # SHT_SYMTAB, SHT_DYNSYM
            continue
        strsec = secs[sh[6]]
        for i in range(sh[5] // 24):
            nm, info, other, shndx, value, size = struct.unpack_from('<IBBHQQ', data, sh[4] + i * 24)
            if shndx == 0 or not value:
                continue
            n = data[strsec[4] + nm:data.index(b'\0', strsec[4] + nm)].decode()
            syms.setdefault(n, value)
    return syms

def cname(sym):
    return ''.join(c if c.isalnum() else '_' for c in sym)

def main():
    path, name, out = sys.argv[1], sys.argv[2], sys.argv[3]
    opts = {'--export': [], '--hook': []}
    for i in range(4, len(sys.argv), 2):
        opts[sys.argv[i]] = [x for x in sys.argv[i + 1].split(',') if x]
    data = open(path, 'rb').read()
    assert data[:4] == b'\x7fELF' and data[4] == 2, 'need ELF64'
    phoff, = struct.unpack_from('<Q', data, 0x20)
    phentsize, phnum = struct.unpack_from('<HH', data, 0x36)
    loads = []
    for i in range(phnum):
        p_type, p_flags, p_offset, p_vaddr, _, p_filesz, p_memsz, _ = struct.unpack_from('<IIQQQQQQ', data, phoff + i * phentsize)
        if p_type == 1:
            loads.append((p_vaddr, p_offset, p_filesz, p_memsz, p_flags))
    end = max(v + m for v, _, _, m, _ in loads)
    end = (end + PAGE - 1) & ~(PAGE - 1)
    hookpage = end
    if opts['--hook']:
        end += PAGE                      # slots for hooked functions
    w0 = min(v for v, _, _, _, f in loads if f & 2) & ~(PAGE - 1)
    # every non-writable segment must lie below W0, every writable one at or above it
    for v, _, _, m, f in loads:
        assert (f & 2 and v >= w0) or (not f & 2 and v + m <= w0), 'segments interleave'
    img = bytearray(end)
    for v, o, fs, m, f in loads:
        img[v:v + fs] = data[o:o + fs]
    patched = sysregs = 0
    for v, o, fs, m, f in loads:
        if not f & 1:
            continue
        for a in range(v, v + fs - 3, 4):
            w, = struct.unpack_from('<I', img, a)
            rd = w & 31
            if (w & 0xFFFFFFE0) == 0xD53BD040:          # mrs xN, tpidr_el0
                struct.pack_into('<I', img, a, w | 0x20)  # mrs xN, tpidrro_el0
                patched += 1
            elif (w & 0xFFFFFFE0) == 0xD53B0020:        # mrs xN, ctr_el0 (traps on Apple CPUs)
                struct.pack_into('<I', img, a, 0xB20E83E0 | rd)   # orr xN, xzr, #0x0004000400040004 (64-byte lines)
                sysregs += 1
            elif (w & 0xFFFFFFE0) == 0xD53B2520:        # mrs xN, gcspr_el0 (no guarded control stack)
                struct.pack_into('<I', img, a, 0xD2800000 | rd)   # movz xN, #0
                sysregs += 1
    syms = symtab(data) if opts['--export'] or opts['--hook'] else {}
    header = [f'// generated by elf2macho.py from {os.path.basename(path)}', '#pragma once']
    for sym in opts['--export']:
        header.append(f'#define ELF_{name}_{cname(sym)} {syms[sym]:#x}  // {sym}')
    for i, sym in enumerate(opts['--hook']):
        a = syms[sym] & ~1
        slot = hookpage + 8 * i
        pg = ((slot & ~0xfff) - (a & ~0xfff)) >> 12
        adrp = 0x90000010 | ((pg & 3) << 29) | (((pg >> 2) & 0x7ffff) << 5)
        ldr = 0xF9400210 | (((slot & 0xfff) // 8) << 10)
        struct.pack_into('<III', img, a, adrp, ldr, 0xD61F0200)
        header.append(f'#define HOOK_{name}_{cname(sym)} {slot:#x}  // {sym}')
    os.makedirs(out, exist_ok=True)
    open(os.path.join(out, f'{name}_syms.h'), 'w').write('\n'.join(header) + '\n')
    open(os.path.join(out, f'{name}.x.bin'), 'wb').write(img[:w0])
    open(os.path.join(out, f'{name}.w.bin'), 'wb').write(img[w0:])
    with open(os.path.join(out, f'{name}.s'), 'w') as s:
        s.write(f'''// generated by elf2macho.py from {os.path.basename(path)}
	.section __ELFX,__elfx,regular,pure_instructions
	.p2align 14
	.globl _elf_{name}_base
_elf_{name}_base:
	.incbin "{name}.x.bin"
	.section __ELFW,__elfw
	.p2align 14
	.globl _elf_{name}_wbase
_elf_{name}_wbase:
	.incbin "{name}.w.bin"
''')
    print(f'{name}: {patched} thread-pointer reads + {sysregs} system-register reads patched, image {end:#x} bytes, code [0,{w0:#x}), data [{w0:#x},{end:#x})')

main()
